#!/bin/bash
# COSMIC desktop -> Void Linux aarch64 xbps build kit
set -euo pipefail
KIT="$(cd "$(dirname "$0")" && pwd)"
. "$KIT/config.sh"
LOCK="$KIT/versions.lock"
REPO_ARCH="$ARCH"; [ "$LIBC" = musl ] && REPO_ARCH="$ARCH-musl"

comps() { grep -v '^\s*#' "$KIT/components.psv" | grep -v '^\s*$'; }
log() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }

xsrc() {
	local a=()
	[ "$(uname -m)" != "$ARCH" ] && a=(-A "$ARCH")   # emulated via qemu-user-static
	(cd "$VP_DIR" && ./xbps-src -j"$JOBS" "${a[@]}" "$@")
}

cmd_setup() {
	log "Preparing void-packages at $VP_DIR"
	[ -d "$VP_DIR/.git" ] || git clone --depth 1 "$VP_URL" "$VP_DIR"
	local a=(); [ "$(uname -m)" != "$ARCH" ] && a=(-A "$ARCH")
	(cd "$VP_DIR" && ./xbps-src "${a[@]}" binary-bootstrap)
}

cmd_versions() {
	log "Resolving latest stable tags"
	: > "$LOCK"
	comps | while IFS='|' read -r name repo pre _ _; do
		tags=$(git ls-remote --tags --refs "https://github.com/pop-os/$repo" 2>/dev/null \
			| sed 's#.*refs/tags/##' | grep "^${pre}[0-9]" || true)
		stable=$(echo "$tags" | grep -v -- '-' || true)
		pick=$(echo "${stable:-$tags}" | sed "s#^${pre}##" | sort -V | tail -1)
		[ -n "$pick" ] || { echo "!! no tag for $name" >&2; continue; }
		echo "$name=$pick" | tee -a "$LOCK"
	done
}

cmd_gen() {
	[ -s "$LOCK" ] || cmd_versions
	log "Generating templates"
	local all=""
	comps | while IFS='|' read -r name repo pre extra desc; do
		ver=$(grep "^$name=" "$LOCK" | cut -d= -f2) || true
		[ -n "${ver:-}" ] || { echo "skip $name (no version)"; continue; }
		d="$VP_DIR/srcpkgs/$name"; mkdir -p "$d"
		url="https://github.com/pop-os/$repo/archive/refs/tags/${pre}${ver}.tar.gz"
		sha=$(curl -fsSL "$url" | sha256sum | cut -d' ' -f1)
		{
			cat <<T
# Generated by cosmic-void-kit
pkgname=$name
version=$ver
revision=1
archs="aarch64* x86_64*"
wrksrc="$repo-${pre}\${version}"
hostmakedepends="cargo rust just pkg-config clang cmake git nasm"
makedepends="$(echo $COMMON_MAKEDEPS $extra)"
short_desc="$(echo $desc)"
maintainer="$MAINTAINER"
license="GPL-3.0-only"
homepage="https://github.com/pop-os/$repo"
distfiles="$url"
checksum=$sha

T
			cat "$KIT/templates/body.tpl"
		} > "$d/template"
		echo "  $name $ver"
	done
	# meta package
	local deps; deps=$(comps | cut -d'|' -f1 | tr '\n' ' ')
	mkdir -p "$VP_DIR/srcpkgs/cosmic-desktop"
	cat > "$VP_DIR/srcpkgs/cosmic-desktop/template" <<T
pkgname=cosmic-desktop
version=1.0
revision=1
build_style=meta
depends="$deps greetd dbus elogind polkit xdg-user-dirs xorg-server-xwayland noto-fonts-ttf"
short_desc="COSMIC desktop environment (meta package)"
maintainer="$MAINTAINER"
license="GPL-3.0-only"
homepage="https://system76.com/cosmic"
T
}

cmd_build() {
	log "Building (this takes a long time)"
	comps | cut -d'|' -f1 | while read -r n; do
		[ -d "$VP_DIR/srcpkgs/$n" ] || continue
		log "pkg $n"; xsrc pkg "$n"
	done
	xsrc pkg cosmic-desktop
}

cmd_repo() {
	log "Collecting packages into $OUT_DIR"
	mkdir -p "$OUT_DIR"
	cp -v "$VP_DIR"/hostdir/binpkgs/*/*.xbps "$VP_DIR"/hostdir/binpkgs/*.xbps "$OUT_DIR"/ 2>/dev/null || true
	xbps-rindex -a "$OUT_DIR"/*.xbps
	cat <<M

Done. On the target Void ($REPO_ARCH) machine:
  echo 'repository=file://$OUT_DIR' | sudo tee /etc/xbps.d/cosmic-local.conf
  sudo xbps-install -S cosmic-desktop
(or serve $OUT_DIR over HTTP and use its URL; add --unsigned handling or sign with xbps-rindex -s/-S)
M
}

case "${1:-all}" in
	setup) cmd_setup;; versions) cmd_versions;; gen) cmd_gen;;
	build) cmd_build;; repo) cmd_repo;;
	one) shift; xsrc pkg "$1";;
	all) cmd_setup; cmd_versions; cmd_gen; cmd_build; cmd_repo;;
	*) echo "usage: $0 {all|setup|versions|gen|build|repo|one <pkg>}"; exit 1;;
esac
